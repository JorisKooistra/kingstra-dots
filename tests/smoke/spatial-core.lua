local core = assert(loadfile("config/hypr/lua/spatial/core.lua"))()
local config = assert(loadfile("config/hypr/lua/spatial/config.lua"))()
local passed = 0

local function test(name, fn)
    local ok, err = pcall(fn)
    if not ok then
        io.stderr:write("FAIL: " .. name .. "\n" .. tostring(err) .. "\n")
        os.exit(1)
    end
    passed = passed + 1
    print("ok - " .. name)
end

local function equal(actual, expected, label)
    if actual ~= expected then
        error((label or "value") .. ": expected " .. tostring(expected) .. ", got " .. tostring(actual))
    end
end

local function fresh(ids, active)
    local state = core.new_state()
    core.sync(state, ids, active, config)
    return state
end

local AREA = { x = 0, y = 0, w = 1000, h = 800 }

-- Zet B via een zet omlaag in een eigen cel onder A.
local function two_rows()
    local state = fresh({ "A", "B" }, "B")
    assert(core.move(state, "down", config))
    return state
end

test("first window starts at origin", function()
    local state = fresh({ "A" }, "A")
    equal(core.position_of(state, "A").col, 0)
    equal(core.position_of(state, "A").row, 0)
end)

test("twelve windows stay on the same page with no four-window cap", function()
    local ids={}
    for i=1,12 do ids[i]="W"..i end
    local state=fresh(ids,"W1")
    local boxes=core.placements(state,AREA,config)
    equal(#core.members(state,0,0),12)
    for _,id in ipairs(ids) do
        equal(core.position_of(state,id).col,0)
        equal(core.position_of(state,id).row,0)
        assert(boxes[id] and boxes[id].w>0 and boxes[id].h>0,id.." missing")
    end
end)

test("a new window opens on the empty spot the camera looks at", function()
    local state = fresh({ "A" }, "A")
    core.sync(state, { "A" }, "A", config, AREA)
    assert(core.pan(state, "up"))
    core.sync(state, { "A", "B" }, "B", config, AREA)
    equal(core.position_of(state, "B").col, 0)
    equal(core.position_of(state, "B").row, -1)
    equal(state.camera.row, -1, "camera stays on the new window")
end)

test("a new window lands where free dragging stopped", function()
    local state = fresh({ "A" }, "A")
    core.sync(state, { "A" }, "A", config, AREA)
    assert(core.pan_by(state, 990, 0, AREA, config))
    core.settle(state, AREA, config)
    core.sync(state, { "A", "B" }, "B", config, AREA)
    equal(core.position_of(state, "B").col, 1)
    equal(core.position_of(state, "B").row, 0)
end)

test("moving down creates a second row", function()
    local state = two_rows()
    equal(core.position_of(state, "B").col, 0)
    equal(core.position_of(state, "B").row, 1)
    equal(state.camera.row, 1)
end)

test("moving into an occupied cell adds a tile", function()
    local state = two_rows()
    assert(core.move(state, "up", config))
    equal(core.position_of(state, "B").row, 0)
    equal(core.position_of(state, "A").row, 0)
    local placements = core.placements(state, AREA, config)
    assert(placements.A.x < placements.B.x, "tiles sit side by side")
end)

test("moving into an occupied page adds a tile without displacing another app", function()
    local state=fresh({"A","B","C","D","E","F"},"F")
    core.move(state,"right",config)
    equal(#core.members(state,0,0),5)
    core.move(state,"left",config)
    equal(#core.members(state,0,0),6)
    equal(#core.members(state,1,0),0)
end)

test("the map places a window on any spot", function()
    local state = fresh({ "A", "B" }, "A")
    assert(core.place(state, "B", 2, -1, config))
    equal(core.position_of(state, "B").col, 2)
    equal(core.position_of(state, "B").row, -1)
    assert(core.place(state, "A", 2, -1, config))
    equal(#core.members(state, 2, -1), 2, "dropping on a window makes tiles")
    assert(not core.place(state, "A", 2, -1, config), "same spot is a no-op")
end)

test("the map can drop a window on a chosen tile spot", function()
    local state = fresh({ "A", "B", "C" }, "A")
    assert(core.place(state, "C", 0, 0, config, 0), "reorder inside the same spot")
    equal(core.members(state, 0, 0)[1], "C")
    equal(core.members(state, 0, 0)[2], "A")
end)

test("a dragged window lands where it is dropped, not last", function()
    local state = fresh({ "A", "B", "C" }, "A")
    core.sync(state, { "A", "B", "C" }, "A", config, AREA)
    local col, row = state.camera.col, state.camera.row
    -- Super+slepen: C wordt even zwevend en verdwijnt uit de layout.
    core.sync(state, { "A", "B" }, "C", config, AREA)
    equal(state.camera.col, col, "camera stays while dragging")
    equal(state.camera.row, row, "camera stays while dragging")
    -- Loslaten links in het werkvlak: C wordt de eerste tegel.
    core.sync(state, { "A", "B", "C" }, "C", config, AREA, { x = 20, y = 400 })
    equal(core.members(state, 0, 0)[1], "C")
    equal(state.camera.col, col, "camera stays after the drop")
end)

test("a dropped window can go to an empty spot", function()
