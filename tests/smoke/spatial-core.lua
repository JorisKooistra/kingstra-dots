test("a small left tile swaps into the large right tile without changing its size", function()
    local state = fresh({"A", "B", "C"}, "A")
    core.placements(state, AREA, config)
    assert(core.toggle_split(state, AREA, config))
    -- A/B in de gekozen boom omwisselen werkt ongeacht welke kant groot is.
    local before = core.placements(state, AREA, config)
    assert(core.tile_place(state,"C","A","center",AREA,config))
    local after = core.placements(state, AREA, config)
    for _, field in ipairs({"x","y","w","h"}) do
        equal(after.C[field],before.A[field],"C takes A's complete "..field)
        equal(after.A[field],before.C[field],"A takes C's complete "..field)
    end
end)

test("drop at each edge splits that exact tile and preserves the other tile", function()
    for _, edge in ipairs({"left","right","up","down"}) do
        local state=fresh({"A","B","C"},"C")
        local before=core.placements(state,AREA,config)
        assert(core.tile_place(state,"C","A",edge,AREA,config))
        local p=core.placements(state,AREA,config)
        equal(math.min(p.A.x,p.C.x),before.A.x)
        equal(math.min(p.A.y,p.C.y),before.A.y)
        equal(math.max(p.A.x+p.A.w,p.C.x+p.C.w),before.A.x+before.A.w)
        equal(math.max(p.A.y+p.A.h,p.C.y+p.C.h),before.A.y+before.A.h)
        if edge=="left" then assert(p.C.x<p.A.x); equal(p.C.h,p.A.h)
        elseif edge=="right" then assert(p.C.x>p.A.x); equal(p.C.h,p.A.h)
        elseif edge=="up" then assert(p.C.y<p.A.y); equal(p.C.w,p.A.w)
        else assert(p.C.y>p.A.y); equal(p.C.w,p.A.w) end
        equal(state.camera.col,0);equal(state.camera.row,0)
        assert(p.B.w>0 and p.B.h>0)
    end
end)

