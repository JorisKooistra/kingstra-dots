test("dwindle ratios and split directions survive recalculation and closing a sibling", function()
    local state = fresh({"A", "B", "C"}, "B")
    local initial = core.placements(state, AREA, config)
    assert(core.resize_by(state, 80, 50, AREA, config))
    local resized = core.placements(state, AREA, config)
    assert(resized.A.w > initial.A.w and resized.B.h > initial.B.h)
    core.sync(state, {"A", "B", "C"}, "B", config, AREA)
    equal(core.placements(state, AREA, config).B.h, resized.B.h)
    assert(core.toggle_split(state, AREA, config))
    local rotated = core.placements(state, AREA, config)
    equal(rotated.B.y, rotated.C.y)
    assert(rotated.B.x < rotated.C.x)
    core.sync(state, {"A", "B"}, "B", config, AREA)
    local closed = core.placements(state, AREA, config)
    equal(closed.A.w, resized.A.w)
    equal(closed.B.h, AREA.h)
end)

test("camera dragging never changes tile positions, splits or sizes", function()
    local state = fresh({"A", "B", "C"}, "A")
    local before = core.placements(state, AREA, config)
    local positions = {}
    for id, p in pairs(state.positions) do positions[id] = {col=p.col,row=p.row} end
    core.pan_by(state, 123, -47, AREA, config)
    local after = core.placements(state, AREA, config)
    for id, p in pairs(before) do
        equal(after[id].w, p.w, id .. " width")
        equal(after[id].h, p.h, id .. " height")
        equal(after[id].x, p.x - 123, id .. " x")
        equal(after[id].y, p.y + 47, id .. " y")
        equal(state.positions[id].col, positions[id].col)
        equal(state.positions[id].row, positions[id].row)
    end
end)

test("zoomed drop can reach a neighbouring page outside native screen bounds", function()
    local state=fresh({"A","B"},"A")
    core.place(state,"B",1,0,config)
    local before=core.placements(state,AREA,config)
    local x,y=before.B.x+before.B.w/2,before.B.y+before.B.h/2
    assert(x>AREA.w)
    equal(core.spot_at(state,AREA,config,x,y,"A"),nil)
    local spot=core.spot_at(state,AREA,config,x,y,"A",true)
    equal(spot.target,"B")
    equal(spot.edge,"center")
    core.tile_place(state,"A",spot.target,spot.edge,AREA,config)
    local after=core.placements(state,AREA,config)
    equal(state.positions.A.col,1)
    equal(state.positions.B.col,1)
    assert(after.A.x>after.B.x)
    equal(after.A.h,after.B.h)
    equal(#core.members(state,0,0),0)
    equal(state.camera.col,0)
end)

